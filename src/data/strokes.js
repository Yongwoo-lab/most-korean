// Stroke order for the basic jamo and the compound vowels, drawn in a 100 × 100 box.
// Each stroke is a list of points in writing direction.

function circle(cx, cy, r, steps = 24) {
  // Starts at the top and goes counter-clockwise, as Korean children learn ㅇ.
  const pts = [];
  for (let i = 0; i <= steps; i++) {
    const a = -Math.PI / 2 - (i / steps) * Math.PI * 2;
    pts.push([cx + r * Math.cos(a), cy + r * Math.sin(a)]);
  }
  return pts;
}

