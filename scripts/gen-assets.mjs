// Generates the picture assets the app uses, so only what is needed ships.
//   src/components/icons.js  line icons (lucide-react, ISC) named anywhere in src
//   public/pics/*.svg        colour pictures (Microsoft Fluent Emoji, MIT)
// Run with `npm run assets` after adding a new icon or picture name.
import { readFileSync, readdirSync, writeFileSync, mkdirSync, rmSync, statSync } from "node:fs";
import { join } from "node:path";
import { createRequire } from "node:module";
import * as lucide from "lucide-react";

const require = createRequire(import.meta.url);

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : /\.(jsx?|mjs)$/.test(f) && f !== "icons.js" ? [p] : [];
  });
}
const sources = walk("src").map((f) => readFileSync(f, "utf8")).join("\n");

// Line icons
const names = [...new Set([...sources.matchAll(/["']([A-Z][A-Za-z0-9]*)["']/g)].map((m) => m[1]))]
  .filter((n) => lucide[n] && lucide[n].$$typeof)
  .sort();
writeFileSync(
  "src/components/icons.js",
  `// Generated by scripts/gen-assets.mjs from the icon names used in src (lucide-react, ISC license).\nimport {\n${names.map((n) => `  ${n},`).join("\n")}\n} from "lucide-react";\n\nexport const ICONS = { ${names.join(", ")} };\n`,
);

// Colour pictures: every name in src/data/pictures.js plus pic("...") calls.
const emoji = require("@iconify-json/fluent-emoji/icons.json");
const resolve = (n) => emoji.icons[n] || (emoji.aliases?.[n] && emoji.icons[emoji.aliases[n].parent]);
const picNames = new Set([
  ...[...readFileSync("src/data/pictures.js", "utf8").matchAll(/"([a-z0-9-]+)"/g)].map((m) => m[1]),
  ...[...sources.matchAll(/pic(?:=|:\s*)["']([a-z0-9-]+)["']/g)].map((m) => m[1]),
]);
rmSync("public/pics", { recursive: true, force: true });
mkdirSync("public/pics", { recursive: true });
const missing = [];
let bytes = 0;
for (const n of picNames) {
  const icon = resolve(n);
  if (!icon) {
    missing.push(n);
    continue;
  }
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${icon.width || emoji.width || 32} ${icon.height || emoji.height || 32}">${icon.body}</svg>`;
  bytes += svg.length;
  writeFileSync(`public/pics/${n}.svg`, svg);
}
console.log(`${names.length} line icons, ${picNames.size - missing.length} pictures (${Math.round(bytes / 1024)} KB)`);
if (missing.length) console.log("Not found (ignored):", missing.join(" "));
